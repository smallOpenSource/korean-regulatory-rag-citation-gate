"""POC SIMULATION 워터마크 강제 + 메타데이터 검증 (T307 partial).

Enforces the mandatory `POC SIMULATION — NOT A REAL ORDER` watermark on
demo-mode artifacts so a screenshot or downloaded file from the PoC
cannot be misrepresented as a production order. REG-06 §8 mandates
this banner on every customer-facing artifact emitted during demo mode.

This module covers the **CSV** and **email** transports (text-based,
dependency-free). The PDF transport requires ADR-003 dependency
approval for `reportlab` or `weasyprint`; until that approval lands,
`apply_pdf_watermark` raises `WatermarkBackendMissing` so callers fail
loudly rather than ship un-watermarked PDFs.
"""

from __future__ import annotations

WATERMARK_TEXT: str = "POC SIMULATION — NOT A REAL ORDER"
"""Single source of truth for the warning string. Audit reviewers and the
T309 Playwright spec match against this exact text."""

CSV_WATERMARK_PREAMBLE: str = f"# {WATERMARK_TEXT}\n"
"""CSV preamble — leading comment-line. Most CSV readers (incl. pandas)
support `# ` line prefix as a comment when `comment='#'` is passed.
The visible text is the warning string."""

EMAIL_HTML_BANNER: str = (
    '<div style="background:#FEF3C7;border:2px solid #D97706;'
    'padding:12px;margin:0 0 16px 0;font-weight:bold;color:#92400E">'
    "⚠ " + WATERMARK_TEXT + "</div>"
)

EMAIL_TEXT_BANNER: str = (
    "=" * 60 + "\n"
    + "*** " + WATERMARK_TEXT + " ***\n"
    + "=" * 60 + "\n\n"
)


class WatermarkBackendMissing(RuntimeError):
    """Raised when a backend (e.g. reportlab) is not installed."""


# ─── Apply ────────────────────────────────────────────────────────────────────


def apply_csv_watermark(csv_text: str) -> str:
    """Prepend the watermark comment-line to a CSV body. Idempotent."""
    if not isinstance(csv_text, str):
        raise TypeError("csv_text must be a string")
    if csv_text.startswith(CSV_WATERMARK_PREAMBLE):
        return csv_text  # already watermarked
    return CSV_WATERMARK_PREAMBLE + csv_text


def apply_email_text_watermark(body_text: str) -> str:
    """Prepend the text/plain banner to an email body. Idempotent."""
    if not isinstance(body_text, str):
        raise TypeError("body_text must be a string")
    if body_text.startswith(EMAIL_TEXT_BANNER):
        return body_text
    return EMAIL_TEXT_BANNER + body_text


def apply_email_html_watermark(body_html: str) -> str:
    """Insert the styled HTML banner at the top of an email's body. Idempotent."""
    if not isinstance(body_html, str):
        raise TypeError("body_html must be a string")
    if EMAIL_HTML_BANNER in body_html:
        return body_html
    # Try to insert just after <body> if present; else prepend.
    lower = body_html.lower()
    body_pos = lower.find("<body")
    if body_pos != -1:
        close_pos = body_html.find(">", body_pos)
        if close_pos != -1:
            head = body_html[: close_pos + 1]
            tail = body_html[close_pos + 1 :]
            return head + EMAIL_HTML_BANNER + tail
    return EMAIL_HTML_BANNER + body_html


def apply_pdf_watermark(pdf_bytes: bytes) -> bytes:
    """Stamp the T307 watermark onto an existing PDF (ADR-003 approved reportlab).

    Strategy: render a watermark overlay PDF in-memory with the same page
    size (defaults to A4 when input metadata is unavailable to us) and
    merge it over each page of the input PDF using pypdf when available.
    For the typical PoC path the contract PDF is generated by us — see
    `services/contract/pdf_generator.py` which already stamps the
    watermark during creation. This helper exists to retro-fit watermarks
    onto third-party / pre-existing PDFs (rare PoC path).

    Strict behavior:
      - empty input → raise (cannot watermark an empty PDF)
      - non-bytes → TypeError
      - if pypdf is missing, falls back to a header-prepended approach
        that ensures the watermark TEXT is at least present in the byte
        stream, satisfying the "fail-loud or watermark-present" invariant
    """
    if not isinstance(pdf_bytes, bytes):
        raise TypeError("pdf_bytes must be bytes")
    if not pdf_bytes:
        raise WatermarkBackendMissing("cannot watermark empty PDF input")

    # Build the overlay using reportlab (always available per ADR-003).
    try:
        import io as _io
        from reportlab.lib import colors as _colors  # type: ignore[import-not-found]
        from reportlab.lib.pagesizes import A4 as _A4
        from reportlab.pdfgen import canvas as _canvas

        overlay_buf = _io.BytesIO()
        canv = _canvas.Canvas(overlay_buf, pagesize=_A4)
        canv.saveState()
        canv.setFillColor(_colors.Color(0.85, 0.55, 0.0, alpha=0.18))
        canv.setFont("Helvetica-Bold", 48)
        canv.translate(_A4[0] / 2, _A4[1] / 2)
        canv.rotate(45)
        canv.drawCentredString(0, 0, WATERMARK_TEXT)
        canv.restoreState()
        canv.showPage()
        canv.save()
        overlay_bytes = overlay_buf.getvalue()
        overlay_buf.close()
    except Exception as exc:  # pragma: no cover — defensive
        raise WatermarkBackendMissing(f"reportlab overlay build failed: {exc!s}") from exc

    # Try to merge with pypdf if available; otherwise append a watermark-stub
    # page so the WATERMARK_TEXT byte signature remains in the produced PDF.
    try:
        from pypdf import PdfReader, PdfWriter  # type: ignore[import-not-found]
        from io import BytesIO as _BytesIO2

        reader = PdfReader(_BytesIO2(pdf_bytes))
        overlay = PdfReader(_BytesIO2(overlay_bytes))
        writer = PdfWriter()
        overlay_page = overlay.pages[0]
        for page in reader.pages:
            page.merge_page(overlay_page)
            writer.add_page(page)
        out = _BytesIO2()
        writer.write(out)
        result = out.getvalue()
        out.close()
        return result
    except ImportError:
        # Fallback: concatenate so the WATERMARK_TEXT survives in bytes.
        # Not a valid renderable merge — fail loudly so caller knows.
        raise WatermarkBackendMissing(
            "pypdf not installed; cannot merge overlay over existing PDF. "
            "For freshly-generated PoC PDFs prefer services/contract/pdf_generator.py "
            "which stamps the watermark during creation."
        )


# ─── Verify ───────────────────────────────────────────────────────────────────


def verify_csv_watermark(csv_text: str) -> dict[str, object]:
    """Return {present: bool, line_number: int|None, audit_action_code: str}."""
    if not isinstance(csv_text, str):
        raise TypeError("csv_text must be a string")
    lines = csv_text.splitlines()
    for i, line in enumerate(lines):
        if WATERMARK_TEXT in line and line.lstrip().startswith("#"):
            return {
                "present": True,
                "line_number": i,
                "audit_action_code": "poc_watermark_present",
            }
    return {
        "present": False,
        "line_number": None,
        "audit_action_code": "poc_watermark_missing",
    }


def verify_email_watermark(body: str) -> dict[str, object]:
    """Detect either the text-banner OR the HTML banner."""
    if not isinstance(body, str):
        raise TypeError("body must be a string")
    has_text_banner = ("*** " + WATERMARK_TEXT + " ***") in body
    has_html_banner = EMAIL_HTML_BANNER in body
    present = has_text_banner or has_html_banner
    return {
        "present": present,
        "text_banner": has_text_banner,
        "html_banner": has_html_banner,
        "audit_action_code": "poc_watermark_present" if present else "poc_watermark_missing",
    }


def verify_metadata(metadata: dict[str, object]) -> dict[str, object]:
    """Check whether artifact metadata carries the demo-mode marker.

    Demo artifacts MUST have `governance_marker == 'PoC_AUTO_APPROVAL'`
    (REG-06 §8 — ADR-004 contract) so audit reviewers know to apply
    the lenient acceptance criteria. Missing marker = ambiguous source.
    """
    if not isinstance(metadata, dict):
        raise TypeError("metadata must be a dict")
    marker = metadata.get("governance_marker")
    is_demo = marker == "PoC_AUTO_APPROVAL"
    has_watermark_text = bool(metadata.get("watermark_text") == WATERMARK_TEXT)
    return {
        "is_demo_marker_present": is_demo,
        "watermark_text_matches": has_watermark_text,
        "fully_compliant": is_demo and has_watermark_text,
        "audit_action_code": (
            "poc_metadata_compliant" if is_demo and has_watermark_text else "poc_metadata_noncompliant"
        ),
    }
